# ---------- 文件名 ----------
# 命名规则不能改：OSS 上已经按这套名字存了对象，改名等于全部 404。
# 缩略图名跟着 media.make_thumb 的规则走 —— 去扩展名 + .jpg。

def photo_name(ti, pi, k):
    """第 ti 个行程、第 pi 个点、第 k 张照片的文件名（三个下标都从 0 起）。"""
    return 'test_%d_%d_%d.jpg' % (ti + 1, pi + 1, k + 1)


def thumb_name(filename):
    """media.make_thumb 的命名规则：原名去扩展名 + .jpg。"""
    return filename.rsplit('.', 1)[0] + '.jpg'


