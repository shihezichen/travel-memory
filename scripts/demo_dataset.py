def all_photo_names():
    """按 TRIPS 推出全部照片文件名，顺序跟 seed 写库的顺序一致。"""
    out = []
    for ti, t in enumerate(TRIPS):
        for pi, (pname, lat, lng, pdate, nphoto, pdesc) in enumerate(t['points']):
            for k in range(nphoto):
                out.append((photo_name(ti, pi, k), pname, k))
    return out
